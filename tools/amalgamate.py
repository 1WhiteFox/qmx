LOCAL_INC_RE = re.compile(r'^\s*#include\s+"(?:\.\./include/)?qmx[^"]*\.h"\s*$')

FEATURE_PREAMBLE = """#if !defined(_WIN32) && !defined(__DJGPP__)
    #ifndef _FILE_OFFSET_BITS
        #define _FILE_OFFSET_BITS 64
    #endif
    #ifndef _DEFAULT_SOURCE
        #define _DEFAULT_SOURCE
    #endif
    #if !defined(_POSIX_C_SOURCE) && !defined(_XOPEN_SOURCE)
        #define _POSIX_C_SOURCE 200809L
    #endif
#endif
"""


def strip_feature_block(text: str) -> str:
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines):
        if lines[i].strip() == "#if !defined(_WIN32) && !defined(__DJGPP__)":
            depth = 1
            j = i + 1
            while j < len(lines) and depth > 0:
                s = lines[j].strip()
                if s.startswith("#if"):
                    depth += 1
                elif s.startswith("#endif"):
                    depth -= 1
                j += 1
            block = "\n".join(lines[i:j])
            if "_POSIX_C_SOURCE" in block or "_FILE_OFFSET_BITS" in block or "_DEFAULT_SOURCE" in block:
                i = j
                continue
        out.append(lines[i])
        i += 1
    return "\n".join(out)


def clean_unit(path: str) -> str:
    with open(path, "r", encoding="utf-8") as f:
        text = f.read().replace("\r\n", "\n")
    text = strip_feature_block(text)
    lines = [ln for ln in text.splitlines() if not LOCAL_INC_RE.match(ln)]
    return "\n".join(lines).strip()


def build_amalgamation(out_dir: str):
    os.makedirs(out_dir, exist_ok=True)
    hdr_path = os.path.join(out_dir, "qmx.h")
    src_path = os.path.join(out_dir, "qmx.c")

    hdr_parts = [
        "/* QMX Runtime Amalgamated Header (auto-generated by tools/amalgamate.py) */",
        "#ifndef QMX_AMALGAMATED_H",
        "#define QMX_AMALGAMATED_H",
        FEATURE_PREAMBLE.strip(),
    ]
    for h in HEADERS:
        hdr_parts.append(f"\n/* --- {h} --- */\n" + clean_unit(h))
    hdr_parts.append("\n#endif /* QMX_AMALGAMATED_H */\n")
    hdr_text = "\n".join(hdr_parts)

    src_parts = [
        "/* QMX Runtime Amalgamated Source (auto-generated by tools/amalgamate.py) */",
        FEATURE_PREAMBLE.strip(),
        '#include "qmx.h"',
    ]
    for s in SOURCES:
        src_parts.append(f"\n/* --- {s} --- */\n" + clean_unit(s))
    src_parts.append("")
    src_text = "\n".join(src_parts)

    with open(hdr_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(hdr_text)
    with open(src_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(src_text)

    print(
        f"[OK] Amalgamated -> {hdr_path} ({len(hdr_text) / 1024.0:.1f} KB, {hdr_text.count(chr(10))} lines), "
        f"{src_path} ({len(src_text) / 1024.0:.1f} KB, {src_text.count(chr(10))} lines)"
    )


if __name__ == "__main__":
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "dist"
    build_amalgamation(out_dir)
